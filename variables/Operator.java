package variables;

public class Operator {
    public static void main(String[] args) {
        int x=3;
        x+=3;
        System.out.println(x);
        x-=3;
        System.out.println(x);
        x*=3;
        System.out.println(x);
        x%=3;
        System.out.println(x);
        x/=3;
        System.out.println(x);
        x&=3;
        System.out.println(x);
        x|=3;
        System.out.println(x);
        x^=3;
        System.out.println(x);
        x>>=3;
        System.out.println(x);
        x<<=3;
        System.out.println(x);
    }
}
